type ReportInput = Omit<
  SafetyReport,
  'sifPotential' | 'analysis' | 'originalAnalysis' | 'recommendations' | 'originalRecommendations'
> & { recommendations?: string[] }

function report(seed: ReportInput): SafetyReport {
  const analysis = evaluateSif(seed)
  const recommendations = seed.recommendations ?? suggestControls(seed)
  return {
    ...seed,
    sifPotential: analysis.potential,
    analysis,
    originalAnalysis: structuredClone(analysis),
    recommendations,
    originalRecommendations: [...recommendations],
  }
}

